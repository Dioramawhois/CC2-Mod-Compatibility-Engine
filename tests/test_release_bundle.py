def test_release_sdk_sources_match_certified_crlf_and_generated_inputs(reviewed_native_source):
    from tools.package_release import native_runtime_assets

    root, sdk, folder, calls = reviewed_native_source
    files, components, source = native_runtime_assets(root, sdk)
    assert len(components) == 5
    assert files[folder.relative_to(root).as_posix() + "/dinput8.dll"].startswith(b"a reviewed")
    assert calls[0][0][-1] == "a" * 40
    with zipfile.ZipFile(io.BytesIO(source)) as archive:
        assert archive.read("CC2X-source/src/runtime.c") == b"source\r\n"
        assert (
            archive.read("CC2X-source/build/unified/generated/sdk_data.h") == b"generated bytes\r\n"
        )
        assert not any(name.endswith(".dll") for name in archive.namelist())


@pytest.mark.parametrize(
    "corruption", ["runtime", "generated", "dirty", "commit", "source", "license"]
)
def test_release_rejects_uncertified_sdk_inputs(reviewed_native_source, corruption):
    from tools.package_release import native_runtime_assets

    root, sdk, folder, _ = reviewed_native_source
    report = json.loads((folder / "dinput8.build.json").read_text())
    if corruption == "runtime":
        (folder / "dinput8.dll").write_bytes(b"changed")
    elif corruption == "generated":
        (sdk / "build/unified/generated/sdk_data.h").write_bytes(b"changed")
    elif corruption == "license":
        (folder / "libcxx-LICENSE.txt").unlink()
    else:
        if corruption == "dirty":
            report["source_dirty"] = True
        elif corruption == "commit":
            report["source_commit"] = "b" * 40
        else:
            report["source_sha256"]["src/runtime.c"] = "c" * 64
        (folder / "dinput8.build.json").write_text(json.dumps(report))
    with pytest.raises(ValueError):
        native_runtime_assets(root, sdk)


