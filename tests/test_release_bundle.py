def test_sdk_toolchain_source_archive_checks_compiler_and_keeps_runtime_licenses(
    reviewed_native_source,
):
    from tools.package_release import native_toolchain_sources, sha

    root, sdk, folder, _ = reviewed_native_source
    zig = sdk / "zig.exe"
    zig.write_bytes(b"compiler is hashed, never executed")
    (sdk / "lib/libcxx").mkdir(parents=True)
    (sdk / "lib/libcxx/LICENSE.TXT").write_bytes(b"C++ runtime license")
    (sdk / "LICENSE").write_bytes(b"provider license")
    report_path = folder / "dinput8.build.json"
    report = json.loads(report_path.read_text())
    report["compiler_sha256"] = sha(zig.read_bytes())
    report_path.write_text(json.dumps(report))
    files = native_toolchain_sources(root, zig)
    assert files["Zig-0.15.2/lib/libcxx/LICENSE.TXT"] == b"C++ runtime license"
    assert "zig.exe" not in str(files.keys())
    assert json.loads(files["SOURCE-MANIFEST.json"])["compiler_sha256"] == sha(zig.read_bytes())
    zig.write_bytes(b"changed")
    with pytest.raises(ValueError, match="checksum"):
        native_toolchain_sources(root, zig)
    with pytest.raises(ValueError, match="--zig"):
        native_toolchain_sources(root, None)


